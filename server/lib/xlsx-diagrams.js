// The workbook's Diagrams tab, and the scope labelling of every other tab.
//
// WHY THIS IS A SEPARATE FILE. Two reasons, and the second is the important
// one. It is self-contained — it needs nothing from xlsx-gen.js but the
// workbook object and the loaded data — and xlsx-gen.js is a 5,000-line file
// several people work in at once. Everything here is reachable through ONE call
// at the end of buildWorkbook, so this feature cannot be half-applied.
//
// WHY THE DIAGRAM IS DRAWN IN CELLS AND NOT EMBEDDED AS A PICTURE. ExcelJS
// embeds png/jpeg/gif buffers only. Nothing in this repo can produce one: the
// Mermaid renderer and the icon-canvas engine are BROWSER code (web/js/pages/
// diagrams.js, web/js/diagram-canvas.js), the server has no rasteriser, and
// adding one means adding a dependency. SVG cannot be embedded either — Excel
// does not accept it through ExcelJS. So the choice was: an empty tab, a broken
// image, or drawing the diagram out of what a spreadsheet actually has — cells,
// fills and borders. This draws it, and ships the Mermaid source alongside so
// the rendered version can be regenerated anywhere that speaks Mermaid.
//
// What the tab contains, top to bottom:
//   1. the region pair            primary ══► recovery (the scoped environment's
//                                 own pair when the export is environment-scoped)
//   2. RESTORE ORDER              every component in scope as a card, banded by
//                                 restore layer, L0 first
//   3. RESTORE CHAINS             per Tier-0/1 component, the chain of things
//                                 that must be back before it, left to right
//   4. WHAT THIS SCOPE HIDES      scoped exports only — the findings that fell
//                                 outside the scope, named
//   5. MERMAID SOURCE             the same graph as text, one line per row

// ------------------------------------------------------------------ palette
// Deliberately duplicated from xlsx-gen.js rather than imported: these are six
// hex strings, and duplicating them is cheaper than coupling two files that
// different people edit.
const INK = 'FF202124';
const WHITE = 'FFFFFFFF';
const MUTED = 'FF5F6368';
const HEADER_GREEN = 'FF3C6958';
const PARENT_FILL = 'FFF1F3F4';
const TINT = {
  ok: { fill: 'FFE6F4EA', font: 'FF137333' },
  err: { fill: 'FFFCE8E6', font: 'FFA50E0E' },
  warn: { fill: 'FFFEF7E0', font: 'FFB06000' },
};
const ARIAL = (extra = {}) => ({ name: 'Arial', size: 10, ...extra });
const solid = (argb) => ({ type: 'pattern', pattern: 'solid', fgColor: { argb } });

const LAYER_LABELS = {
  L0: 'L0 guardrails/backups green', L1: 'L1 recovery launch/replication',
  L2: 'L2 platform', L3: 'L3 data + secrets', L4: 'L4 applications',
  L5: 'L5 edge/network reachability', L6: 'L6 functional success bar',
  L7: 'L7 live traffic cutover',
};
const layerOrder = (l) => {
  const n = parseInt(String(l || '').replace(/^L/i, ''), 10);
  return Number.isFinite(n) ? n : 99;
};
const LAYER_FILL = {
  L0: 'FFE8F0FE', L1: 'FFE6F4EA', L2: 'FFFFF3E0', L3: 'FFFCE8E6',
  L4: 'FFF3E8FD', L5: 'FFE0F7FA', L6: 'FFF1F3F4', L7: 'FFFFF8E1',
};
const layerFill = (l) => LAYER_FILL[String(l || '').toUpperCase()] || 'FFF8F9FA';

const plural = (n, word) => `${n} ${word}${n === 1 ? '' : 's'}`;
const bits = (...parts) => parts.filter((p) => p !== null && p !== undefined && p !== '').join(' · ');
const str = (v) => (v === null || v === undefined ? '' : String(v));

export const DIAGRAMS_SHEET = 'Diagrams';

const DIA_COLS = 13;   // column 1 is a margin; 2..13 carry six 2-wide cards
const DIA_SPAN = 2;
const DIA_PER_ROW = 6;

const thin = (argb) => ({ style: 'thin', color: { argb } });
const boxBorder = (argb = 'FFBDC1C6') => ({
  top: thin(argb), left: thin(argb), bottom: thin(argb), right: thin(argb),
});

// ------------------------------------------------------------------ mermaid

// Mermaid node ids must be stable and syntactically safe; the label keeps the
// real name. A quote inside a label would end the label, so it is stripped.
const mmdId = (id, i) => `n${i}_${str(id).replace(/[^A-Za-z0-9]/g, '')}`.slice(0, 40);
const mmdLabel = (s) => str(s).replace(/["\\]/g, '').replace(/\s+/g, ' ').trim() || '(unnamed)';

function diagramsMermaid(meta, components, label) {
  const inScope = new Set(components.map((c) => c.id));
  const idOf = new Map(components.map((c, i) => [c.id, mmdId(c.id, i)]));
  const L = [];
  L.push(`%% ${meta.name || meta.slug || 'workspace'} — restore order${label ? ` — ${label}` : ''}`);
  L.push('%% Generated by DR Compass. Paste into Lucidchart (Insert → Diagram as code),');
  L.push('%% a GitHub/GitLab/Notion mermaid code block, or the DR Compass Diagrams page.');
  L.push('flowchart TD');

  const byLayer = new Map();
  for (const c of components) {
    const k = c.restoreLayer || '';
    if (!byLayer.has(k)) byLayer.set(k, []);
    byLayer.get(k).push(c);
  }
  for (const layer of [...byLayer.keys()].sort((a, b) => layerOrder(a) - layerOrder(b))) {
    const name = layer ? (LAYER_LABELS[layer] || layer) : 'No restore layer recorded';
    L.push(`  subgraph ${layer || 'LX'}["${mmdLabel(name)}"]`);
    for (const c of byLayer.get(layer)) {
      L.push(`    ${idOf.get(c.id)}["${mmdLabel(c.name)}${c.tier != null ? ` · T${c.tier}` : ''}"]`);
    }
    L.push('  end');
  }

  const MAX_EDGES = 300;
  let edges = 0;
  let dropped = 0;
  for (const c of components) {
    for (const dep of c.dependsOn || []) {
      if (!inScope.has(dep)) continue;
      if (edges >= MAX_EDGES) { dropped += 1; continue; }
      L.push(`  ${idOf.get(dep)} --> ${idOf.get(c.id)}`);   // arrow runs the way recovery does
      edges += 1;
    }
  }
  if (dropped) {
    L.push(`%% ${dropped} further edge(s) omitted at the ${MAX_EDGES}-edge cap —`);
    L.push('%% the Dependencies sheet carries every one of them.');
  }
  return { lines: L, edges, dropped, nodes: components.length };
}

// The longest restore path ending at `root`: walk dependencies, always taking
// the one that has to come back earliest. Cycle-safe by construction.
function restoreChain(root, byId, inScope, maxHops = 5) {
  const path = [root];
  const seen = new Set([root.id]);
  let cur = root;
  while (path.length <= maxHops) {
    const deps = (cur.dependsOn || [])
      .map((id) => byId.get(id))
      .filter((c) => c && !seen.has(c.id) && inScope.has(c.id))
      .sort((a, b) => layerOrder(a.restoreLayer) - layerOrder(b.restoreLayer)
        || (a.tier ?? 9) - (b.tier ?? 9));
    if (!deps.length) break;
    cur = deps[0];
    seen.add(cur.id);
    path.push(cur);
  }
  return path.reverse();   // restore order: first back, first
}

// --------------------------------------------------------------- the labels

/** `adjudication service, Prod environment` — empty unless env/service-scoped. */
export function scopeSuffix(scope) {
  if (!scope) return '';
  const parts = [
    scope.serviceName ? `${scope.serviceName} service` : '',
    scope.envName ? `${scope.envName} environment` : '',
  ].filter(Boolean);
  if (!parts.length) return '';
  // An EMPTY scope says so on every sheet. The alternative is a workbook titled
  // "prod / adjudication" whose sheets are blank for a reason nobody can see.
  return ` — ${parts.join(', ')}${scope.empty ? ' · EMPTY SCOPE: nothing is assigned to it yet' : ''}`;
}

// ---------------------------------------------------------------- the sheet

function addDiagramsSheet(wb, d, scope, deploy) {
  const ws = wb.addWorksheet(DIAGRAMS_SHEET, {
    views: [{ state: 'frozen', ySplit: 1, zoomScale: 85, showGridLines: false }],
    properties: { tabColor: { argb: HEADER_GREEN } },
  });
  ws.getColumn(1).width = 3;
  for (let i = 2; i <= DIA_COLS; i++) ws.getColumn(i).width = 15;

  const meta = d.meta || {};
  const components = [...(d.components || [])].sort((a, b) =>
    layerOrder(a.restoreLayer) - layerOrder(b.restoreLayer)
    || (a.tier ?? 9) - (b.tier ?? 9)
    || str(a.name).localeCompare(str(b.name)));
  const inScope = new Set(components.map((c) => c.id));
  const byId = d.byId || new Map(components.map((c) => [c.id, c]));

  // ---- primitives -------------------------------------------------------
  const line = (text, o = {}) => {
    const r = ws.addRow([]);
    r.height = o.height || 15;
    ws.mergeCells(r.number, 1, r.number, DIA_COLS);
    const c = r.getCell(1);
    c.value = text;
    c.font = o.mono
      ? { name: 'Courier New', size: 8.5, color: { argb: o.color || MUTED } }
      : ARIAL({ size: o.size || 10, bold: !!o.bold, italic: !!o.italic, color: { argb: o.color || INK } });
    c.alignment = {
      vertical: 'middle', horizontal: o.align || 'left', wrapText: !!o.wrap, indent: o.indent ?? 1,
    };
    if (o.fill) for (let i = 1; i <= DIA_COLS; i++) r.getCell(i).fill = solid(o.fill);
    return r;
  };
  const gap = (h = 6) => { const r = ws.addRow([]); r.height = h; return r; };
  const section = (text, note) => {
    gap(10);
    line(text, { bold: true, size: 12, fill: PARENT_FILL, height: 22 });
    if (note) line(note, { size: 9, color: MUTED, height: 26, wrap: true });
  };
  const cardRow = (items) => {
    const r = ws.addRow([]);
    r.height = items.some((i) => str(i.text).length > 26) ? 34 : 28;
    items.slice(0, DIA_PER_ROW).forEach((it, j) => {
      const col = 2 + j * DIA_SPAN;
      ws.mergeCells(r.number, col, r.number, col + DIA_SPAN - 1);
      for (let k = col; k < col + DIA_SPAN; k++) {
        const cell = r.getCell(k);
        cell.fill = solid(it.fill || 'FFF8F9FA');
        cell.border = boxBorder(it.edge);
      }
      const cell = r.getCell(col);
      cell.value = it.text;
      cell.font = ARIAL({ size: 9, bold: !!it.bold, color: { argb: it.color || INK } });
      cell.alignment = { vertical: 'middle', horizontal: 'center', wrapText: true };
    });
    return r;
  };

  // CONTEXT components are the ones the scope did not ask for and cannot
  // recover without. Drawn grey and labelled, so a dependency that was dragged
  // in is never read as part of the service someone scoped to.
  const contextIds = new Set(scope?.contextIds || []);
  const isContext = (c) => contextIds.has(c.id);
  const cardText = (c) => [
    c.name,
    bits(c.kind || c.category || '', c.tier != null ? `T${c.tier}` : '', isContext(c) ? 'dependency' : ''),
  ].filter(Boolean).join('\n');

  // ---- title + scope ----------------------------------------------------
  line(`Diagrams — ${meta.name || meta.slug || 'workspace'}`
    + `${scope?.rootName ? ` · ${scope.rootName}` : ''}${scopeSuffix(scope)}`,
  { bold: true, size: 14, height: 28 });
  line('The high-level picture, drawn in cells so it survives being printed, mailed and opened in Google Sheets. '
    + 'Read it top to bottom: the bands come back in that order. The Mermaid source at the bottom regenerates the '
    + 'rendered version anywhere that speaks Mermaid.',
  { size: 9, color: MUTED, wrap: true, height: 30 });
  if (scope?.sentence) {
    line(`SCOPE — ${scope.sentence}`, {
      size: 9.5, bold: true, wrap: true, height: 30, fill: TINT.ok.fill, color: TINT.ok.font,
    });
  }

  if (!components.length) {
    // Never an empty tab: say why it is empty and what to do about it.
    section('NOTHING IS IN SCOPE, SO THERE IS NOTHING TO DRAW');
    line(scope
      ? 'No component in this workspace is assigned to this environment/service yet. Nothing auto-assigns — assign '
        + 'components on the Inventory page, or with the bulk assign on the Environments page, and export again. '
        + 'This tab is empty because of missing assignment, not because the system has no parts.'
      : 'This workspace has no components yet. Every diagram DR Compass draws comes from the inventory, so there is '
        + 'nothing to draw until there is one — import or discover an inventory first.',
    { wrap: true, height: 46, color: TINT.warn.font, fill: TINT.warn.fill });
    pageSetup(ws, meta, scope);
    return ws;
  }

  // ---- 1. the region pair ----------------------------------------------
  // An environment is a different account and a different region pair, so an
  // environment-scoped workbook must not draw the workspace's default.
  const envRegions = scope?.envRegions && (scope.envRegions.primary || scope.envRegions.recovery)
    ? scope.envRegions : null;
  const regions = envRegions || meta.regions || {};
  section('REGION PAIR — WHERE IT RUNS, AND WHERE IT COMES BACK',
    envRegions ? `The ${scope.envName} environment's own region pair — not the workspace default.` : null);
  cardRow([
    { text: `PRIMARY\n${regions.primary || 'not set'}`, bold: true, fill: TINT.ok.fill, color: TINT.ok.font },
    { text: '══►', bold: true, fill: WHITE, edge: 'FFFFFFFF', color: MUTED },
    { text: `RECOVERY\n${regions.recovery || 'not set'}`, bold: true, fill: TINT.warn.fill, color: TINT.warn.font },
    { text: `${plural(components.length, 'component')}\nin this workbook`, fill: PARENT_FILL, color: MUTED },
  ]);
  if (contextIds.size) {
    line(`Grey cards marked "dependency" (${contextIds.size}) are not part of this scope — they are here because `
      + 'recovering it depends on them. Bold cards are Tier 0/1.',
    { size: 9, color: MUTED, wrap: true, height: 24 });
  }

  // ---- 2. restore layer bands ------------------------------------------
  const waveCount = (deploy?.waves || []).filter((w) => w && (w.categories || []).length).length;
  section('RESTORE ORDER — EACH BAND COMES BACK BEFORE THE ONE BELOW IT',
    'One card per component, banded by restore layer. An empty band is not drawn; a component with no layer '
    + 'recorded is in the last band and says so, because "unknown" is a finding, not a blank.'
    + (waveCount ? ` The deployment-order engine splits the same set into ${plural(waveCount, 'build wave')} — that is the Deployment Order sheet.` : ''));

  const byLayer = new Map();
  for (const c of components) {
    const k = c.restoreLayer || '';
    if (!byLayer.has(k)) byLayer.set(k, []);
    byLayer.get(k).push(c);
  }
  const layerKeys = [...byLayer.keys()].sort((a, b) => layerOrder(a) - layerOrder(b));
  layerKeys.forEach((layer, i) => {
    const items = byLayer.get(layer);
    const label = layer
      ? (LAYER_LABELS[layer] || layer)
      : 'NO RESTORE LAYER RECORDED — nobody has said when these come back';
    line(`${layer ? `${layer} · ` : ''}${label}  (${plural(items.length, 'component')})`,
      { bold: true, size: 10, fill: layerFill(layer), height: 18 });
    for (let j = 0; j < items.length; j += DIA_PER_ROW) {
      cardRow(items.slice(j, j + DIA_PER_ROW).map((c) => ({
        text: cardText(c),
        fill: layerFill(layer),
        bold: (c.tier ?? 9) <= 1 && !isContext(c),
        color: str(c.inRecoveryScope) === 'no' ? TINT.err.font : isContext(c) ? MUTED : INK,
      })));
    }
    if (i < layerKeys.length - 1) line('▼   then', { size: 9, color: MUTED, height: 13, indent: 2 });
  });

  // ---- 3. restore chains -------------------------------------------------
  const roots = components
    .filter((c) => (c.tier ?? 9) <= 1 && (c.dependsOn || []).some((id) => inScope.has(id)))
    .slice(0, 10);
  section('RESTORE CHAINS — WHAT HAS TO BE BACK BEFORE THE RIGHT-HAND BOX HELPS ANYONE',
    'Each line is one Tier-0/Tier-1 component and the deepest chain of dependencies beneath it, in restore order: '
    + 'leftmost comes back first, the component itself last. Chains stop at five hops — the Dependencies sheet '
    + 'carries the full tree.');
  if (!roots.length) {
    line('No Tier-0/Tier-1 component in this scope depends on anything else in it. Either the tiering is not filled '
      + 'in, or this scope is a set of independent parts — check the Dependencies sheet before assuming the second.',
    { wrap: true, height: 30, color: TINT.warn.font, fill: TINT.warn.fill });
  }
  for (const root of roots) {
    const chain = restoreChain(root, byId, inScope);
    const items = [];
    chain.forEach((c, i) => {
      if (i) items.push({ text: '→', fill: WHITE, edge: 'FFFFFFFF', color: MUTED, bold: true });
      items.push({
        text: cardText(c),
        fill: layerFill(c.restoreLayer),
        bold: c.id === root.id,
        color: c.id === root.id ? TINT.ok.font : INK,
      });
    });
    cardRow(items);
  }

  // ---- 4. what this scope hides -----------------------------------------
  if (scope && (scope.hiddenSentences || []).length) {
    const loud = !!(scope.hidden && (scope.hidden.blockerOrHighGaps || scope.hidden.failedTests));
    section('WHAT THIS SCOPE HIDES — READ BEFORE CALLING THIS PACKAGE CLEAN',
      'Narrowing to one environment or service removes every finding filed against everything else. These lines are '
      + 'what a whole-workspace export would have shown you and this one does not.');
    for (const s of scope.hiddenSentences) {
      line(`• ${s}`, {
        wrap: true, height: 32, size: 9.5,
        fill: loud ? TINT.err.fill : null, color: loud ? TINT.err.font : INK,
      });
    }
    for (const w of scope.warnings || []) {
      line(`• ${w}`, { wrap: true, height: 32, size: 9.5, fill: TINT.warn.fill, color: TINT.warn.font });
    }
    if ((scope.dangling || []).length) {
      line(`• Dependency ids in this scope that point at nothing: ${scope.dangling.join(', ')} — `
        + 'a hole in the restore order, not a tidy edge.',
      { wrap: true, height: 24, size: 9.5, fill: TINT.err.fill, color: TINT.err.font });
    }
  }

  // ---- 5. mermaid source -------------------------------------------------
  const mmd = diagramsMermaid(meta, components, scope?.label || '');
  section('MERMAID SOURCE — REGENERATE THE RENDERED DIAGRAM ANYWHERE',
    `The ${mmd.nodes}-node, ${mmd.edges}-edge graph above as Mermaid text. Select these rows, copy, and paste into `
    + 'Lucidchart (Insert → Diagram as code → Mermaid), a mermaid code block on GitHub/GitLab/Notion, or the DR '
    + 'Compass Diagrams page. The DR Package ships the same graph as diagrams/*.mmd next to a rendered .svg and an '
    + 'editable .drawio.');
  for (const l of mmd.lines) line(l, { mono: true, height: 12 });

  pageSetup(ws, meta, scope);
  return ws;
}

// Landscape, fit to one page wide, with the workspace and the scope in the
// header/footer — the bands are meant to be read on paper.
function pageSetup(ws, meta, scope) {
  const amp = (s) => str(s).replace(/&/g, '&&');
  const label = [scope?.serviceName ? `${scope.serviceName} service` : '',
    scope?.envName ? `${scope.envName} environment` : '', scope?.rootName || ''].filter(Boolean).join(' · ');
  ws.pageSetup = {
    ...(ws.pageSetup || {}),
    orientation: 'landscape',
    fitToPage: true,
    fitToWidth: 1,
    fitToHeight: 0,
    printTitlesRow: '1:1',
    margins: { left: 0.4, right: 0.4, top: 0.6, bottom: 0.6, header: 0.3, footer: 0.3 },
  };
  ws.headerFooter = {
    differentFirst: false,
    differentOddEven: false,
    oddHeader: `&L&"Arial,Bold"&11${amp(meta.name || 'DR Compass')}&R&"Arial,Regular"&9Diagrams`,
    oddFooter: `&L&"Arial,Regular"&8Generated ${new Date().toISOString().slice(0, 10)} by DR Compass`
      + `${label ? ` · ${amp(label)}` : ''}`
      + '&C&"Arial,Regular"&8Page &P of &N&R&"Arial,Regular"&8Diagrams',
  };
}

// ------------------------------------------------------------- the one call

/**
 * Add the Diagrams tab and label every sheet with the scope it was built for.
 *
 * Called once, at the end of buildWorkbook:
 *
 *   decorateWorkbook(wb, d, { scope: scopeOpts, deploy, after: 'How to use' });
 *
 * `scope` is the object server/lib/export-scope.js produced (or null/undefined
 * for a whole-workspace export). With no scope this adds the Diagrams tab and
 * changes nothing else — no title, no footer and no workbook property moves.
 *
 * Never throws: a workbook that loses its Diagrams tab to a bug is still a
 * workbook, and the caller is a download someone is waiting on.
 */
export function decorateWorkbook(wb, d, { scope = null, deploy = null, after = 'How to use' } = {}) {
  try {
    const sheet = addDiagramsSheet(wb, d, scope, deploy);
    placeAfter(wb, sheet, after);
  } catch (e) {
    console.error(`[drcompass] Diagrams tab skipped: ${e && e.message ? e.message : e}`);
  }
  try {
    labelScopedSheets(wb, d, scope);
  } catch (e) {
    console.error(`[drcompass] scope labelling skipped: ${e && e.message ? e.message : e}`);
  }
  try {
    announceInGuide(wb);
  } catch { /* the guide row is never load-bearing */ }
  try {
    if (scope && scope.empty) flagEmptyScope(wb, scope);
  } catch { /* the banner is never load-bearing */ }
  return wb;
}

// An empty scope filters every scope-aware sheet down to nothing — but not every
// sheet is scope-aware: the deployment-order engine, for one, falls back to the
// whole workspace when it is handed a scope it cannot satisfy. A sheet that
// still has rows under an empty scope is therefore showing rows that are NOT
// this scope's, and it has to say so where a reader will hit it.
function flagEmptyScope(wb, scope) {
  const label = [scope.serviceName ? `${scope.serviceName} service` : '',
    scope.envName ? `${scope.envName} environment` : ''].filter(Boolean).join(', ') || 'this scope';
  for (const ws of wb.worksheets) {
    if (ws.name === DIAGRAMS_SHEET || ws.rowCount <= 2) continue;
    const row = ws.addRow([]);
    row.height = 30;
    const cols = Math.max(1, ws.columnCount);
    ws.mergeCells(row.number, 1, row.number, cols);
    for (let i = 1; i <= cols; i++) row.getCell(i).fill = solid(TINT.err.fill);
    const cell = row.getCell(1);
    cell.value = `EMPTY SCOPE — nothing in this workspace is assigned to ${label}. Any rows above that are not blank `
      + 'come from a sheet that could not honour the scope and fell back to the whole workspace; they are NOT this '
      + 'scope\'s. Assign components to it and export again.';
    cell.font = ARIAL({ bold: true, size: 9.5, color: { argb: TINT.err.font } });
    cell.alignment = { vertical: 'middle', horizontal: 'left', wrapText: true, indent: 1 };
  }
}

// The How-to-use sheet lists every tab; a tab missing from it reads as an
// accident. Appended rather than woven in, because that sheet belongs to
// xlsx-gen.js and this is a guest row — if its shape ever changes, this
// silently does nothing instead of corrupting it.
function announceInGuide(wb) {
  const ws = wb.getWorksheet('How to use');
  if (!ws || ws.columnCount !== 4 || ws.rowCount < 3) return;
  const first = ws.getRow(3);
  if (typeof first.getCell(1).value !== 'number') return;   // not the Id grid we expect
  for (let r = 3; r <= ws.rowCount; r++) {
    if (String(ws.getRow(r).getCell(2).value || '') === DIAGRAMS_SHEET) return;  // already listed
  }
  const row = ws.addRow([
    ws.rowCount - 1,
    DIAGRAMS_SHEET,
    'The picture. The region pair, then every component as a card banded by restore layer (L0 first), then the '
    + 'restore chain under each Tier-0/1 component, then the Mermaid source that regenerates the rendered version '
    + 'in Lucidchart, GitHub or Notion. It is drawn in cells, so it prints and it survives Google Sheets.',
    'Drawn from this inventory; a scoped workbook says so at the top',
  ]);
  row.height = 32;
  for (let i = 1; i <= 4; i++) {
    const cell = row.getCell(i);
    cell.font = ARIAL({ bold: i === 2, color: { argb: INK } });
    cell.alignment = { vertical: 'top', horizontal: i === 1 ? 'right' : 'left', wrapText: i !== 1 };
  }
  if (ws.autoFilter && ws.autoFilter.to) ws.autoFilter = { ...ws.autoFilter, to: { row: ws.rowCount, column: 4 } };
}

// ExcelJS orders sheets by `orderNo` (Workbook#worksheets sorts on it, and the
// writer walks that getter), so a sheet created last can still be placed third.
function placeAfter(wb, sheet, afterName) {
  const sheets = wb.worksheets.filter((w) => w !== sheet);
  const at = sheets.findIndex((w) => w.name === afterName);
  const ordered = at === -1
    ? [...sheets, sheet]
    : [...sheets.slice(0, at + 1), sheet, ...sheets.slice(at + 1)];
  ordered.forEach((w, i) => { w.orderNo = i + 1; });
}

// Every sheet's title row says what the workbook was scoped to. A page printed
// out of a prod/adjudication workbook has to carry that on its own, because
// someone will read it with no idea which workbook it came from.
function labelScopedSheets(wb, d, scope) {
  const suffix = scopeSuffix(scope);
  if (!suffix) return;                       // unscoped: nothing is touched
  const label = [scope.serviceName ? `${scope.serviceName} service` : '',
    scope.envName ? `${scope.envName} environment` : '', scope.rootName || ''].filter(Boolean).join(' · ');

  for (const ws of wb.worksheets) {
    if (ws.name === DIAGRAMS_SHEET) continue;   // already carries it
    const cell = ws.getCell('A1');
    const current = typeof cell.value === 'string' ? cell.value : null;
    if (current && !current.includes(suffix.trim())) cell.value = current + suffix;
    // …and in the printed footer, where the scope used to appear only for a
    // component-scoped package.
    const hf = ws.headerFooter;
    if (hf && typeof hf.oddFooter === 'string' && !hf.oddFooter.includes(label)) {
      hf.oddFooter = hf.oddFooter.replace('&C&"Arial,Regular"&8Page', `· ${label.replace(/&/g, '&&')}&C&"Arial,Regular"&8Page`);
    }
  }
  const name = (d.meta && (d.meta.name || d.meta.slug)) || '';
  wb.title = `DR package — ${label}${name ? ` (${name})` : ''}`;
}
